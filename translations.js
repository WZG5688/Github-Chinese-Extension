  function unitCn(u) {
    u = String(u).toLowerCase();
    if (u.indexOf('second') === 0) return '秒';
    if (u.indexOf('minute') === 0) return '分钟';
    if (u.indexOf('hour') === 0) return '小时';
    if (u.indexOf('day') === 0) return '天';
    if (u.indexOf('week') === 0) return '周';
    if (u.indexOf('month') === 0) return '个月';
    if (u.indexOf('year') === 0) return '年';
    return u;
  }
  function cnDate(s) {
    const months = { jan: '1', feb: '2', mar: '3', apr: '4', may: '5', jun: '6', jul: '7', aug: '8', sep: '9', oct: '10', nov: '11', dec: '12' };
    const raw = String(s).trim();
    const m = raw.replace(/\./g, '').match(/^([A-Za-z]+)\s+(\d{1,2}),?\s+(\d{4})$/);
    if (m) {
      const mo = months[m[1].toLowerCase().slice(0, 3)];
      if (mo) return m[3] + '年' + mo + '月' + m[2] + '日';
    }
    return raw;
  }

